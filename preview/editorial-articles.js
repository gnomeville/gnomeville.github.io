const previousArticle = article;
article = function(name) {
  previousArticle(name);
  const sections = editorialArticles[name];
  if (!sections) return;
  const root = document.querySelector('.article');
  if (!root) return;
  const old = root.querySelector('.wikignome-editorial');
  if (old) old.remove();
  const block = document.createElement('section');
  block.className = 'wikignome-editorial';
  block.innerHTML = '<h2>Expanded encyclopedia entry</h2>' + sections.map(([heading, body]) => '<h3>'+esc(heading)+'</h3><p>'+esc(body)+'</p>').join('');
  const ref = [...root.querySelectorAll('h2')].find(x=>x.textContent==='References');
  if (ref) root.insertBefore(block,ref); else root.appendChild(block);
};
